import * as crypto from "crypto";
import * as fs from "fs";
import * as path from "path";
import * as cdk from "aws-cdk-lib";
import * as iam from "aws-cdk-lib/aws-iam";
import * as lambda from "aws-cdk-lib/aws-lambda";
import * as logs from "aws-cdk-lib/aws-logs";
import * as s3 from "aws-cdk-lib/aws-s3";
import * as secretsmanager from "aws-cdk-lib/aws-secretsmanager";
import * as cr from "aws-cdk-lib/custom-resources";
import { Construct } from "constructs";

// The bundle scripts/bundle-handlers.mjs builds from transloadit-credential/handler.ts.
const handlerDir = path.join(__dirname, "transloadit-credential", "handler");

export interface TransloaditCredentialProps {
  /** The Transloadit template credential's name, as the templates name it. */
  readonly credentialName: string;
  /** The bucket Transloadit's /s3/store writes into. */
  readonly bucket: s3.IBucket;
  /** The bucket's region; the stack's by default. */
  readonly bucketRegion?: string;
  /**
   * A Transloadit Auth Key with the template_credentials:read and :write scopes, as JSON
   * {"TRANSLOADIT_AUTH_KEY": "...", "TRANSLOADIT_AUTH_SECRET": "..."}. Filled by hand: the key is
   * made in Transloadit's console, and nothing here can create one.
   */
  readonly apiSecret: secretsmanager.ISecret;
  /** The IAM user's name; generated by default. */
  readonly userName?: string;
  /**
   * Bump to rotate: CloudFormation makes a new key, the custom resource writes it into the
   * credential, then the old key is deleted, all in one deploy. 1 by default.
   */
  readonly keySerial?: number;
  /**
   * Whether the credential goes from Transloadit with the stack: true for one the stack owns
   * outright (a developer's), false (the default) for one templates in use rely on.
   */
  readonly deleteWithStack?: boolean;
}

/**
 * A Transloadit template credential that holds a key CloudFormation makes (QB-4147): an IAM user
 * that may only store into the bucket, its access key, the key's secret in a Secrets Manager
 * secret, and a custom resource that writes the key into the credential through Transloadit's SDK.
 *
 * A hand-made key in a credential is replaced in IAM and forgotten in Transloadit: Quriobot's was
 * deleted in a key rotation (QB-4025) and every upload failed for two weeks. Here the deploy that
 * replaces the key writes it into Transloadit before the old key goes, and a refused write fails
 * the deploy. Transloadit's /s3/store cannot assume a role (key, secret and an optional session
 * token only), so the key is long-lived but narrow.
 *
 * The key's secret reaches the handler only through its secret, never as a property: the
 * provider framework logs each event it relays.
 */
export class TransloaditCredential extends Construct {
  public readonly user: iam.User;
  public readonly keySecret: secretsmanager.Secret;

  constructor(scope: Construct, id: string, props: TransloaditCredentialProps) {
    super(scope, id);
    const { bucket } = props;

    this.user = new iam.User(this, "User", props.userName ? { userName: props.userName } : {});
    // What Transloadit's /s3/store asks for, on the objects only
    this.user.addToPrincipalPolicy(
      new iam.PolicyStatement({
        actions: ["s3:PutObject", "s3:PutObjectAcl", "s3:AbortMultipartUpload"],
        resources: [bucket.arnForObjects("*")],
      })
    );
    // The credential names its region, so Transloadit should not need this; the hand-made keys
    // that worked had it, and a denied lookup would fail every upload.
    this.user.addToPrincipalPolicy(
      new iam.PolicyStatement({ actions: ["s3:GetBucketLocation"], resources: [bucket.bucketArn] })
    );
    const key = new iam.CfnAccessKey(this, "AccessKey", { userName: this.user.userName, serial: props.keySerial ?? 1 });
    this.keySecret = new secretsmanager.Secret(this, "AccessKeySecret", {
      description: `The access key Transloadit's ${props.credentialName} stores with`,
      secretObjectValue: {
        accessKeyId: cdk.SecretValue.unsafePlainText(key.ref),
        secretAccessKey: cdk.SecretValue.resourceAttribute(key.attrSecretAccessKey),
      },
    });

    const provider = TransloaditCredentialProvider.of(this);
    props.apiSecret.grantRead(provider.handler);
    this.keySecret.grantRead(provider.handler);

    new cdk.CustomResource(this, "Resource", {
      serviceToken: provider.serviceToken,
      resourceType: "Custom::TransloaditCredential",
      properties: {
        // a new handler updates the function but not the resource; this makes it run again
        HandlerHash: transloaditHandlerHash(),
        ApiSecretArn: props.apiSecret.secretArn,
        KeySecretArn: this.keySecret.secretArn,
        // not secret; a new key changes it, so a rotation runs the handler
        AccessKeyId: key.ref,
        CredentialName: props.credentialName,
        S3Bucket: bucket.bucketName,
        S3BucketRegion: props.bucketRegion ?? cdk.Stack.of(this).region,
        DeleteWithStack: props.deleteWithStack ? "true" : "false",
      },
    });
  }
}

/**
 * The custom resource provider of a stack's TransloaditCredentials, one per stack. `handler` is
 * there for grants a credential cannot make itself, such as a cross-account API secret's KMS key.
 */
export class TransloaditCredentialProvider extends Construct {
  public static of(scope: Construct): TransloaditCredentialProvider {
    const stack = cdk.Stack.of(scope);
    const id = "TransloaditCredentialProvider";
    const existing = stack.node.tryFindChild(id);
    if (existing === undefined) return new TransloaditCredentialProvider(stack, id);
    if (!(existing instanceof TransloaditCredentialProvider)) {
      throw new Error(`${stack.node.path}/${id} is taken by another construct`);
    }
    return existing;
  }

  public readonly handler: lambda.Function;
  public readonly serviceToken: string;

  private constructor(scope: Construct, id: string) {
    super(scope, id);
    this.handler = new lambda.Function(this, "Handler", {
      runtime: lambda.Runtime.NODEJS_22_X,
      architecture: lambda.Architecture.ARM_64,
      handler: "index.handler",
      code: lambda.Code.fromAsset(handlerDir),
      // a listing and a write: two 8 s requests each, plus one rate-limit wait (the handler's
      // clientOptions)
      timeout: cdk.Duration.minutes(2),
      description: "Writes an IAM key into a Transloadit template credential",
      logGroup: new logs.LogGroup(this, "HandlerLogs", {
        retention: logs.RetentionDays.THREE_MONTHS,
        removalPolicy: cdk.RemovalPolicy.DESTROY,
      }),
    });
    this.serviceToken = new cr.Provider(this, "Provider", {
      onEventHandler: this.handler,
      logGroup: new logs.LogGroup(this, "ProviderLogs", {
        retention: logs.RetentionDays.THREE_MONTHS,
        removalPolicy: cdk.RemovalPolicy.DESTROY,
      }),
    }).serviceToken;
  }
}

function transloaditHandlerHash(): string {
  return crypto.createHash("sha256").update(fs.readFileSync(path.join(handlerDir, "index.mjs"))).digest("hex");
}
